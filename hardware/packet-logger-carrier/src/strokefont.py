ADV = 5.0
CAP = 6.0

def width(s, size):
    return len(s)*ADV*(size/CAP)

def strokes(s, x, y, size, just='center', angle=0):
    """returns list of polylines in mm, anchored so that (x,y) is the
    centre of the text box vertically and per `just` horizontally."""
    u = size/CAP
    total = width(s,size)
    if   just=='center': ox = -total/2
    elif just=='right':  ox = -total
    else:                ox = 0.0
    oy = -size/2
    out=[]
    pen=0.0
    for ch in s:
        g = G.get(ch.upper())
        if g is None: g = G['?']
        for st in g:
            pl=[( (pen+px)*u+ox, py*u+oy ) for (px,py) in st]
            out.append(pl)
        pen += ADV
    ca,sa = math.cos(math.radians(angle)), math.sin(math.radians(angle))
    res=[]
    for pl in out:
        res.append([(x+px*ca-py*sa, y+px*sa+py*ca) for (px,py) in pl])
    return res
